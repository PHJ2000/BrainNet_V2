package com.brainnet.ownership;

import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.annotation.PostConstruct;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.net.http.HttpTimeoutException;
import java.time.Duration;
import java.util.List;
import java.util.Map;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;

@RestController
class NodeController {
    private final JdbcTemplate jdbc;
    private final ObjectMapper mapper = new ObjectMapper();
    private final HttpClient client = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(1)).build();
    private final String providerUrl;
    private final String schema;

    NodeController(JdbcTemplate jdbc,
                   @Value("${PROVIDER_URL:http://provider:8080}") String providerUrl,
                   @Value("${DB_SCHEMA:j}") String schema) {
        this.jdbc = jdbc; this.providerUrl = providerUrl; this.schema = schema;
    }

    record NodeCreate(String content, String ai_prompt, Long parent_id, Integer depth, Integer order,
                      Double pos_x, Double pos_y, Integer provider_delay_ms, Boolean provider_fail) {}
    record NodeView(long id, long project_id, Long author_id, String content, String state,
                    Double pos_x, Double pos_y, int depth, int order_index, Long parent_id, List<Long> tags) {}

    @PostConstruct
    void schema() {
        jdbc.execute("CREATE SCHEMA IF NOT EXISTS " + schema);
        jdbc.execute("CREATE TABLE IF NOT EXISTS " + schema + ".node (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL, parent_id BIGINT, author_id BIGINT, content TEXT NOT NULL, state VARCHAR(16) NOT NULL, depth INT NOT NULL, order_index INT NOT NULL, pos_x DOUBLE PRECISION, pos_y DOUBLE PRECISION)");
    }

    @GetMapping("/health") Map<String, Object> health() {
        return Map.of("status", "ok", "runtime", "spring", "virtual_threads", Thread.currentThread().isVirtual());
    }

    @PostMapping("/projects/{projectId}/nodes")
    @ResponseStatus(HttpStatus.CREATED)
    List<NodeView> create(@PathVariable long projectId, @RequestBody NodeCreate body) {
        String content = body.content();
        String state = "ACTIVE";
        if (body.ai_prompt() != null && !body.ai_prompt().isBlank()) {
            content = generate(body);
            state = "GHOST";
        }
        if (content == null || content.isBlank()) throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "content is required when ai_prompt absent");
        int depth = body.depth() == null ? 0 : body.depth();
        int order = body.order() == null ? 0 : body.order();
        double x = body.pos_x() == null ? 0 : body.pos_x();
        double y = body.pos_y() == null ? 0 : body.pos_y();
        String sql = "INSERT INTO " + schema + ".node(project_id,parent_id,author_id,content,state,depth,order_index,pos_x,pos_y) VALUES (?,?,1,?,?,?,?,?,?) RETURNING *";
        NodeView node = jdbc.queryForObject(sql, (rs, n) -> new NodeView(rs.getLong("id"), rs.getLong("project_id"),
            (Long) rs.getObject("author_id"), rs.getString("content"), rs.getString("state"),
            (Double) rs.getObject("pos_x"), (Double) rs.getObject("pos_y"), rs.getInt("depth"),
            rs.getInt("order_index"), (Long) rs.getObject("parent_id"), List.of()),
            projectId, body.parent_id(), content, state, depth, order, x, y);
        return List.of(node);
    }

    private String generate(NodeCreate body) {
        try {
            String json = mapper.writeValueAsString(Map.of("prompt", body.ai_prompt(),
                "delay_ms", body.provider_delay_ms() == null ? 200 : body.provider_delay_ms(),
                "fail", Boolean.TRUE.equals(body.provider_fail())));
            HttpRequest request = HttpRequest.newBuilder(URI.create(providerUrl + "/generate"))
                .timeout(Duration.ofSeconds(1)).header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString(json)).build();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());
            if (response.statusCode() != 200) throw new ResponseStatusException(HttpStatus.BAD_GATEWAY, "upstream failure");
            JsonNode parsed = mapper.readTree(response.body());
            return parsed.get("content").asText();
        } catch (HttpTimeoutException exception) {
            throw new ResponseStatusException(HttpStatus.GATEWAY_TIMEOUT, "upstream timeout");
        } catch (ResponseStatusException exception) {
            throw exception;
        } catch (InterruptedException exception) {
            Thread.currentThread().interrupt();
            throw new ResponseStatusException(HttpStatus.BAD_GATEWAY, "upstream interrupted");
        } catch (Exception exception) {
            throw new ResponseStatusException(HttpStatus.BAD_GATEWAY, "upstream failure");
        }
    }

    @PostMapping("/benchmark/reset") Map<String, String> reset() {
        jdbc.execute("TRUNCATE " + schema + ".node RESTART IDENTITY");
        return Map.of("status", "ok");
    }

    @GetMapping("/benchmark/state") Map<String, Long> state() {
        Long count = jdbc.queryForObject("SELECT count(*) FROM " + schema + ".node", Long.class);
        return Map.of("nodes", count == null ? 0 : count);
    }
}

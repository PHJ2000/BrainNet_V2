import os
from contextlib import asynccontextmanager

import httpx
from fastapi import FastAPI, HTTPException, WebSocket
from pydantic import BaseModel
from sqlalchemy import text
from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine

SCHEMA = os.getenv("DB_SCHEMA", "fs")
DATABASE_URL = os.getenv("DATABASE_URL", "postgresql+asyncpg://benchmark:benchmark@postgres:5432/ownership")
PROVIDER_URL = os.getenv("PROVIDER_URL", "http://provider:8080")
engine = create_async_engine(DATABASE_URL, pool_size=15, max_overflow=0, pool_timeout=5)
Session = async_sessionmaker(engine, expire_on_commit=False)
client = httpx.AsyncClient(timeout=httpx.Timeout(1.0))


class NodeCreate(BaseModel):
    content: str | None = None
    ai_prompt: str | None = None
    parent_id: int | None = None
    depth: int = 0
    order: int = 0
    pos_x: float = 0.0
    pos_y: float = 0.0
    provider_delay_ms: int = 200
    provider_fail: bool = False


def view(row):
    return {"id": row.id, "project_id": row.project_id, "author_id": row.author_id,
            "content": row.content, "state": row.state, "pos_x": row.pos_x,
            "pos_y": row.pos_y, "depth": row.depth, "order_index": row.order_index,
            "parent_id": row.parent_id, "tags": []}


@asynccontextmanager
async def lifespan(_: FastAPI):
    async with engine.begin() as db:
        await db.execute(text(f"CREATE SCHEMA IF NOT EXISTS {SCHEMA}"))
        await db.execute(text(f"CREATE TABLE IF NOT EXISTS {SCHEMA}.node (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL, parent_id BIGINT, author_id BIGINT, content TEXT NOT NULL, state VARCHAR(16) NOT NULL, depth INT NOT NULL, order_index INT NOT NULL, pos_x DOUBLE PRECISION, pos_y DOUBLE PRECISION)"))
    yield
    await client.aclose()
    await engine.dispose()


app = FastAPI(lifespan=lifespan)


@app.get("/health")
async def health():
    return {"status": "ok", "runtime": "fastapi"}


@app.post("/projects/{project_id}/nodes", status_code=201)
async def create_node(project_id: int, body: NodeCreate):
    content = body.content
    state = "ACTIVE"
    if body.ai_prompt:
        try:
            response = await client.post(f"{PROVIDER_URL}/generate", json={"prompt": body.ai_prompt,
                "delay_ms": body.provider_delay_ms, "fail": body.provider_fail})
        except httpx.TimeoutException:
            raise HTTPException(504, "upstream timeout")
        if response.status_code != 200:
            raise HTTPException(502, "upstream failure")
        content = response.json()["content"]
        state = "GHOST"
    if not content:
        raise HTTPException(400, "content is required when ai_prompt absent")
    async with Session.begin() as db:
        row = (await db.execute(text(f"INSERT INTO {SCHEMA}.node(project_id,parent_id,author_id,content,state,depth,order_index,pos_x,pos_y) VALUES (:pid,:parent,1,:content,:state,:depth,:ord,:x,:y) RETURNING *"),
            {"pid": project_id, "parent": body.parent_id, "content": content, "state": state,
             "depth": body.depth, "ord": body.order, "x": body.pos_x, "y": body.pos_y})).one()
    return [view(row)]


@app.post("/benchmark/reset")
async def reset():
    async with engine.begin() as db:
        await db.execute(text(f"TRUNCATE {SCHEMA}.node RESTART IDENTITY"))
    return {"status": "ok"}


@app.get("/benchmark/state")
async def state():
    async with engine.connect() as db:
        count = (await db.execute(text(f"SELECT count(*) FROM {SCHEMA}.node"))).scalar_one()
    return {"nodes": count}


@app.websocket("/projects/{project_id}/ws")
async def websocket_echo(project_id: str, websocket: WebSocket):
    await websocket.accept()
    while True:
        try:
            await websocket.send_text(await websocket.receive_text())
        except Exception:
            return

package com.brainnet.vertical;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
class SchemaInitializer implements ApplicationRunner {
    private final JdbcTemplate jdbc;
    private final String schema;

    SchemaInitializer(JdbcTemplate jdbc, @Value("${DB_SCHEMA:j}") String schema) {
        if (!schema.matches("[A-Za-z0-9_]+")) throw new IllegalArgumentException("invalid schema");
        this.jdbc = jdbc;
        this.schema = schema;
    }

    @Override public void run(ApplicationArguments args) {
        jdbc.execute("CREATE SCHEMA IF NOT EXISTS " + schema);
        jdbc.execute("CREATE TABLE IF NOT EXISTS " + schema + ".project (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id BIGINT NOT NULL, name VARCHAR(120) NOT NULL, description TEXT, is_deleted BOOLEAN NOT NULL DEFAULT FALSE)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS " + schema + ".project_user_role (project_id BIGINT NOT NULL REFERENCES " + schema + ".project(id) ON DELETE CASCADE, user_id BIGINT NOT NULL, role VARCHAR(16) NOT NULL, PRIMARY KEY(project_id,user_id))");
        jdbc.execute("CREATE TABLE IF NOT EXISTS " + schema + ".node (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL REFERENCES " + schema + ".project(id) ON DELETE CASCADE, parent_id BIGINT REFERENCES " + schema + ".node(id) ON DELETE SET NULL, author_id BIGINT, content TEXT NOT NULL, state VARCHAR(16) NOT NULL, depth INT NOT NULL, order_index INT NOT NULL, pos_x DOUBLE PRECISION, pos_y DOUBLE PRECISION, version INT NOT NULL DEFAULT 0)");
        jdbc.execute("CREATE UNIQUE INDEX IF NOT EXISTS uq_" + schema + "_active_root ON " + schema + ".node(project_id) WHERE parent_id IS NULL AND state='ACTIVE'");
    }
}

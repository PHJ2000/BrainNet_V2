import json
import os
import time
import uuid
from contextvars import ContextVar
from typing import Annotated

from fastapi import FastAPI, Header, HTTPException, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field
from sqlalchemy import text
from sqlalchemy.exc import DBAPIError, IntegrityError
from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine

MODE = os.getenv("APP_MODE", "safe")
SCHEMA = os.getenv("DB_SCHEMA", "fs")
if not SCHEMA.replace("_", "").isalnum():
    raise RuntimeError("invalid schema")

DATABASE_URL = os.getenv(
    "DATABASE_URL", "postgresql+asyncpg://benchmark:benchmark@postgres:5432/vertical"
)
POOL_SIZE = int(os.getenv("DB_POOL_SIZE", "30"))
engine = create_async_engine(
    DATABASE_URL,
    pool_size=POOL_SIZE,
    max_overflow=0,
    pool_timeout=5,
    echo=False,
)
Session = async_sessionmaker(engine, expire_on_commit=False)
trace_ctx: ContextVar[str] = ContextVar("trace_id", default="unknown")
app = FastAPI(title=f"BrainNet vertical slice {MODE}")


class ProjectCreate(BaseModel):
    name: Annotated[str, Field(min_length=1, max_length=120)]
    description: Annotated[str | None, Field(max_length=2000)] = None


class NodeCreate(BaseModel):
    content: Annotated[str, Field(min_length=1, max_length=2000)]
    parent_id: int | None = None
    depth: int = 0
    order: int = 0
    pos_x: float = 0.0
    pos_y: float = 0.0


class NodePatch(BaseModel):
    expected_version: Annotated[int, Field(ge=0)]
    content: Annotated[str, Field(min_length=1, max_length=2000)]
    pos_x: float | None = None
    pos_y: float | None = None


def error(status: int, code: str, message: str) -> JSONResponse:
    return JSONResponse(
        status_code=status,
        content={"code": code, "message": message, "trace_id": trace_ctx.get()},
    )


def node_json(row) -> dict:
    return {
        "id": row.id,
        "project_id": row.project_id,
        "author_id": row.author_id,
        "content": row.content,
        "state": row.state,
        "pos_x": row.pos_x,
        "pos_y": row.pos_y,
        "depth": row.depth,
        "order_index": row.order_index,
        "parent_id": row.parent_id,
        "version": row.version,
    }


@app.middleware("http")
async def tracing(request: Request, call_next):
    supplied_trace = request.headers.get("x-trace-id")
    trace_id = supplied_trace or str(uuid.uuid4())
    token = trace_ctx.set(trace_id)
    request.state.trace_id = trace_id
    started = time.perf_counter()
    try:
        response = await call_next(request)
    except DBAPIError as exc:
        print(json.dumps({"level": "ERROR", "trace_id": trace_id, "code": "DB_ERROR", "error": type(exc).__name__}), flush=True)
        response = error(500, "DB_ERROR", "database operation failed")
    except Exception as exc:
        print(json.dumps({"level": "ERROR", "trace_id": trace_id, "code": "INTERNAL_ERROR", "error": type(exc).__name__}), flush=True)
        response = error(500, "INTERNAL_ERROR", "internal server error")
    response.headers["X-Trace-Id"] = trace_id
    if supplied_trace:
        print(json.dumps({"level": "INFO", "trace_id": trace_id, "method": request.method, "path": request.url.path, "status": response.status_code, "duration_ms": round((time.perf_counter() - started) * 1000, 3)}), flush=True)
    trace_ctx.reset(token)
    return response


@app.exception_handler(RequestValidationError)
async def validation_error(_: Request, exc: RequestValidationError):
    return error(422, "VALIDATION_ERROR", str(exc.errors()[0]["msg"]))


@app.exception_handler(HTTPException)
async def http_error(_: Request, exc: HTTPException):
    code = {404: "NODE_NOT_FOUND", 409: "VERSION_CONFLICT"}.get(exc.status_code, "HTTP_ERROR")
    return error(exc.status_code, code, str(exc.detail))


async def init_schema() -> None:
    unique_sql = (
        f"CREATE UNIQUE INDEX IF NOT EXISTS uq_{SCHEMA}_active_root "
        f"ON {SCHEMA}.node(project_id) WHERE parent_id IS NULL AND state='ACTIVE'"
        if MODE == "safe"
        else f"DROP INDEX IF EXISTS {SCHEMA}.uq_{SCHEMA}_active_root"
    )
    statements = [
        f"CREATE SCHEMA IF NOT EXISTS {SCHEMA}",
        f"CREATE TABLE IF NOT EXISTS {SCHEMA}.project (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, owner_id BIGINT NOT NULL, name VARCHAR(120) NOT NULL, description TEXT, is_deleted BOOLEAN NOT NULL DEFAULT FALSE)",
        f"CREATE TABLE IF NOT EXISTS {SCHEMA}.project_user_role (project_id BIGINT NOT NULL REFERENCES {SCHEMA}.project(id) ON DELETE CASCADE, user_id BIGINT NOT NULL, role VARCHAR(16) NOT NULL, PRIMARY KEY(project_id,user_id))",
        f"CREATE TABLE IF NOT EXISTS {SCHEMA}.node (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL REFERENCES {SCHEMA}.project(id) ON DELETE CASCADE, parent_id BIGINT REFERENCES {SCHEMA}.node(id) ON DELETE SET NULL, author_id BIGINT, content TEXT NOT NULL, state VARCHAR(16) NOT NULL, depth INT NOT NULL, order_index INT NOT NULL, pos_x DOUBLE PRECISION, pos_y DOUBLE PRECISION, version INT NOT NULL DEFAULT 0)",
        unique_sql,
    ]
    async with engine.begin() as conn:
        for statement in statements:
            await conn.execute(text(statement))


@app.on_event("startup")
async def startup():
    await init_schema()


@app.get("/health")
async def health():
    async with engine.connect() as conn:
        await conn.execute(text("SELECT 1"))
    return {"status": "ok", "runtime": "fastapi", "mode": MODE, "pool_size_per_process": POOL_SIZE}


@app.post("/projects", status_code=201)
async def create_project(body: ProjectCreate, x_user_id: int = Header(1), x_benchmark_fault: str | None = Header(None)):
    async with Session.begin() as db:
        project_id = (await db.execute(text(f"INSERT INTO {SCHEMA}.project(owner_id,name,description) VALUES (:uid,:name,:description) RETURNING id"), {"uid": x_user_id, "name": body.name, "description": body.description})).scalar_one()
        await db.execute(text(f"INSERT INTO {SCHEMA}.project_user_role(project_id,user_id,role) VALUES (:pid,:uid,'OWNER')"), {"pid": project_id, "uid": x_user_id})
        if x_benchmark_fault == "db":
            await db.execute(text("SELECT 1/0"))
        await db.execute(text(f"INSERT INTO {SCHEMA}.node(project_id,author_id,content,state,depth,order_index,pos_x,pos_y) VALUES (:pid,:uid,'주제를 입력하세요','ACTIVE',0,0,800,400)"), {"pid": project_id, "uid": x_user_id})
    return {"id": project_id, "owner_id": x_user_id, "name": body.name, "description": body.description}


@app.post("/projects/{project_id}/nodes", status_code=201)
async def create_node(project_id: int, body: NodeCreate, x_user_id: int = Header(1)):
    is_root = body.parent_id in (None, 0)
    async with Session.begin() as db:
        if is_root and MODE == "legacy":
            exists = (await db.execute(text(f"SELECT id FROM {SCHEMA}.node WHERE project_id=:pid AND parent_id IS NULL AND state='ACTIVE' LIMIT 1"), {"pid": project_id})).first()
            if exists:
                raise HTTPException(409, "Root node already exists for this project")
        try:
            row = (await db.execute(text(f"INSERT INTO {SCHEMA}.node(project_id,parent_id,author_id,content,state,depth,order_index,pos_x,pos_y) VALUES (:pid,:parent,:uid,:content,'ACTIVE',:depth,:ord,:x,:y) RETURNING *"), {"pid": project_id, "parent": None if is_root else body.parent_id, "uid": x_user_id, "content": body.content, "depth": body.depth, "ord": body.order, "x": body.pos_x, "y": body.pos_y})).one()
        except IntegrityError:
            raise HTTPException(409, "Root node already exists for this project")
    return node_json(row)


@app.get("/projects/{project_id}/nodes/{node_id}")
async def get_node(project_id: int, node_id: int):
    async with Session() as db:
        row = (await db.execute(text(f"SELECT * FROM {SCHEMA}.node WHERE id=:id AND project_id=:pid"), {"id": node_id, "pid": project_id})).first()
    if not row:
        raise HTTPException(404, "Node not found")
    return node_json(row)


@app.patch("/projects/{project_id}/nodes/{node_id}")
async def patch_node(project_id: int, node_id: int, body: NodePatch, x_benchmark_fault: str | None = Header(None)):
    async with Session.begin() as db:
        if x_benchmark_fault == "db":
            await db.execute(text("SELECT 1/0"))
        version_clause = "AND version=:expected" if MODE == "safe" else ""
        row = (await db.execute(text(f"UPDATE {SCHEMA}.node SET content=:content, pos_x=COALESCE(:x,pos_x), pos_y=COALESCE(:y,pos_y), version=version+1 WHERE id=:id AND project_id=:pid {version_clause} RETURNING *"), {"content": body.content, "x": body.pos_x, "y": body.pos_y, "id": node_id, "pid": project_id, "expected": body.expected_version})).first()
        if not row:
            exists = (await db.execute(text(f"SELECT 1 FROM {SCHEMA}.node WHERE id=:id AND project_id=:pid"), {"id": node_id, "pid": project_id})).first()
            if not exists:
                raise HTTPException(404, "Node not found")
            raise HTTPException(409, "Expected version does not match")
    return node_json(row)


@app.post("/benchmark/reset")
async def reset(nodes: int = 400, root: bool = True):
    async with engine.begin() as db:
        await db.execute(text(f"TRUNCATE {SCHEMA}.node, {SCHEMA}.project_user_role, {SCHEMA}.project RESTART IDENTITY CASCADE"))
        pid = (await db.execute(text(f"INSERT INTO {SCHEMA}.project(owner_id,name) VALUES (1,'benchmark') RETURNING id"))).scalar_one()
        await db.execute(text(f"INSERT INTO {SCHEMA}.project_user_role(project_id,user_id,role) VALUES (:pid,1,'OWNER')"), {"pid": pid})
        first_id = None
        if root:
            first_id = (await db.execute(text(f"INSERT INTO {SCHEMA}.node(project_id,author_id,content,state,depth,order_index,pos_x,pos_y) VALUES (:pid,1,'root','ACTIVE',0,0,0,0) RETURNING id"), {"pid": pid})).scalar_one()
        if nodes > 0:
            inserted = (await db.execute(text(f"INSERT INTO {SCHEMA}.node(project_id,parent_id,author_id,content,state,depth,order_index,pos_x,pos_y) SELECT :pid,:parent,1,'node-'||g,'ACTIVE',1,g,0,0 FROM generate_series(1,:nodes) g RETURNING id"), {"pid": pid, "parent": first_id, "nodes": nodes})).scalars().all()
            first_id = inserted[0]
    return {"project_id": pid, "first_node_id": first_id, "nodes": nodes, "root": root}


@app.get("/benchmark/state")
async def state():
    async with engine.connect() as db:
        row = (await db.execute(text(f"SELECT count(*) FILTER (WHERE parent_id IS NULL AND state='ACTIVE') AS roots, count(*) AS nodes, COALESCE(max(version),0) AS max_version FROM {SCHEMA}.node"))).one()
        projects = (await db.execute(text(f"SELECT count(*) FROM {SCHEMA}.project"))).scalar_one()
        memberships = (await db.execute(text(f"SELECT count(*) FROM {SCHEMA}.project_user_role"))).scalar_one()
    return {"roots": row.roots, "nodes": row.nodes, "max_version": row.max_version, "projects": projects, "memberships": memberships}
